#!/bin/bash
# ==========================================================================
# [AWS EC2 일괄 중지 자동화 프로그램]
# 지정된 리전 내에서 현재 구동 중인(running) 모든 서버의 전원을 안전하게 끕니다.
# ==========================================================================

# [설정] 인스턴스를 중지할 AWS 리전을 지정합니다. (서울 리전 기본값)
TARGET_REGION="ap-northeast-2"

echo "--------------------------------------------------------"
echo "🔍 [1/3] ${TARGET_REGION} 리전에서 가동 중인 EC2 인스턴스를 조회 중..."
echo "--------------------------------------------------------"

# 1. 오직 '실행 중(running)' 상태인 EC2의 인스턴스 ID 목록만 추출합니다.
INSTANCE_IDS=$(aws ec2 describe-instances \
    --region "${TARGET_REGION}" \
    --filters "Name=instance-state-name,Values=running" \
    --query "Reservations[*].Instances[*].InstanceId" \
    --output text)

# 2. 만약 현재 켜져 있는 서버가 하나도 없다면 프로그램을 즉시 종료합니다.
if [ -z "${INSTANCE_IDS}" ] || [ "${INSTANCE_IDS}" == "None" ]; then
    echo "✅ 현재 구동 중인 EC2 인스턴스가 없습니다. 모두 꺼져 있습니다."
    echo "--------------------------------------------------------"
    exit 0
fi

# 3. 오작동 방지를 위해 중지 대상 서버들의 ID 목록을 화면에 보여줍니다.
echo "📋 [중지 대상 리스트]:"
echo "${INSTANCE_IDS}"
echo "--------------------------------------------------------"

# 4. 안전을 위한 최종 수동 확인 절차
read -p "⚠️  정말로 위 목록의 모든 EC2 인스턴스를 중지(전원 종료)하시겠습니까? (yes/no): " CONFIRM
if [ "${CONFIRM}" != "yes" ]; then
    echo "❌ 작업이 사용자에 의해 취소되었습니다."
    echo "--------------------------------------------------------"
    exit 1
fi

echo "--------------------------------------------------------"
echo "🔌 [2/3] EC2 인스턴스 일괄 중지 명령 전송..."
echo "--------------------------------------------------------"

# 5. 추출된 ID 목록을 AWS CLI에 주입하여 일괄 중지(Stop) 명령을 전송합니다.
aws ec2 stop-instances \
    --region "${TARGET_REGION}" \
    --instance-ids ${INSTANCE_IDS} \
    --output table

echo "--------------------------------------------------------"
echo "⏳ [3/3] 모든 서버의 전원이 완전히 꺼질 때까지 대기합니다..."
echo "--------------------------------------------------------"

# 6. AWS 인프라에서 완전히 중지 처리가 완료될 때까지 터미널을 붙잡고 대기(Wait)합니다.
aws ec2 wait instance-stopped \
    --region "${TARGET_REGION}" \
    --instance-ids ${INSTANCE_IDS}

echo "🎉 모든 EC2 인스턴스가 안전하게 중지되었습니다!"
echo "--------------------------------------------------------"

